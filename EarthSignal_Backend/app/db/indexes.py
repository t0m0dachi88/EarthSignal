async def ensure_indexes(db):
    await db["users"].create_index("user_id", unique=True)
    await db["users"].create_index("email", unique=True)
    await db["investigations"].create_index("investigation_id", unique=True)
    await db["investigations"].create_index([("owner_id", 1), ("created_at", -1)])
    await db["analysis_runs"].create_index("job_id", unique=True)
    await db["analysis_runs"].create_index([("status", 1), ("created_at", 1)])
    await db["discoveries"].create_index("discovery_id", unique=True)
    await db["discoveries"].create_index([("target_variable", 1), ("integrated_candidate_flag", 1)])
    await db["trend_results"].create_index("result_id", unique=True)
    await db["trend_results"].create_index("investigation_id", unique=True)
    await db["contrasts"].create_index("contrast_id", unique=True)
    await db["recommendations"].create_index("recommendation_id", unique=True)
    await db["regions"].create_index([("geometry", "2dsphere")])
    await db["observations"].create_index([("dataset_id", 1), ("cell_id", 1), ("year", 1)])
    await db["model_registry"].create_index("artifact_version", unique=True)
    await db["analysis_runs"].create_index([("lease_expires_at", 1)])
